// Writes the CLI reference pages from the command tree `goback docs` prints.
//   goback docs > cli.json && node scripts/cli-reference.mjs cli.json
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const out = 'src/content/docs/reference/cli';
const tree = JSON.parse(readFileSync(process.argv[2] ?? 0, 'utf8'));

const esc = (s = '') => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const cell = (s = '') => esc(s).replace(/\|/g, '\\|').replace(/\n+/g, ' ');

function flagTable(flags = []) {
	if (flags.length === 0) return '';
	const rows = flags.map((f) => {
		const names = f.names.map((n) => '`' + (n.length === 1 ? '-' : '--') + n + (f.takesValue ? ' value' : '') + '`').join(', ');
		const env = (f.env ?? []).map((e) => '`' + e + '`').join(', ');
		const def = f.default ? '`' + f.default + '`' : '';
		return `| ${names} | ${cell(f.usage)} | ${env} | ${def} |`;
	});
	return ['| Flag | Description | Environment | Default |', '| --- | --- | --- | --- |', ...rows, ''].join('\n');
}

function synopsis(path, cmd) {
	const parts = ['goback', '[global flags]', ...path.slice(1)];
	if (cmd.flags?.length) parts.push('[flags]');
	if (cmd.commands?.length) parts.push('<command>');
	else if (cmd.argsUsage) parts.push(cmd.argsUsage);
	return '```sh\n' + parts.join(' ') + '\n```\n';
}

function section(path, cmd, depth) {
	const lines = [];
	if (depth > 0) lines.push(`${'#'.repeat(depth + 1)} ${path.slice(1).join(' ')}`, '');
	const text = cmd.description || cmd.usage;
	if (text) lines.push(esc(text), '');
	if (cmd.aliases?.length) lines.push(`Aliases: ${cmd.aliases.map((a) => '`' + a + '`').join(', ')}`, '');
	lines.push(synopsis(path, cmd));
	const table = flagTable(cmd.flags);
	if (table) lines.push(table);
	for (const sub of cmd.commands ?? []) lines.push(section([...path, sub.name], sub, depth + 1));
	return lines.join('\n');
}

const page = (title, description, order, body) =>
	`---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description ?? '')}\nsidebar:\n  order: ${order}\n---\n\n` +
	'<!-- generated by scripts/cli-reference.mjs from `goback docs`; do not edit -->\n\n' +
	body;

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const index = [
	esc(tree.usage ?? ''),
	'',
	'```sh\ngoback [global flags] <command> [flags] [arguments]\n```',
	'',
	'## Commands',
	'',
	'| Command | Does |',
	'| --- | --- |',
	...tree.commands.map((c) => `| [\`${c.name}\`](./goback-${c.name}/) | ${cell(c.usage || c.description)} |`),
	'',
	'## Global flags',
	'',
	'Global flags go before the command.',
	'',
	flagTable(tree.flags),
].join('\n');
writeFileSync(join(out, 'index.md'), page('goback', tree.usage, 0, index));

tree.commands.forEach((cmd, i) => {
	writeFileSync(join(out, `goback-${cmd.name}.md`), page(`goback ${cmd.name}`, cmd.usage || cmd.description, i + 1, section(['goback', cmd.name], cmd, 0)));
});

console.log(`wrote ${tree.commands.length + 1} pages to ${out}`);
